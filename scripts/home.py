def work_scope():
    controls, spreads = [], []
    for i, (key, label, market, brief, context, outputs) in enumerate(BRIEFS):
        checked = ' checked' if i == 0 else ''
        controls.append(f'<label><input type="radio" name="engagement" value="{key}"{checked}><span>{label}</span></label>')
        rows = ''.join(f'<div><dt>{name}</dt><dd>{copy}</dd></div>' for name, copy in outputs)
        spreads.append(f'''<article class="brief-sheet" data-engagement="{key}"><div class="brief-voice">
        <small>Пример задачи · {market}</small><h3>{brief}</h3><p>{context}</p></div>
        <div class="brief-output"><h4>Что можно подготовить</h4><dl>{rows}</dl></div></article>''')
    return f'''<section class="agency-section work-scope"><div class="wrap" id="scope">
    <header class="scope-lead"><h2>Что продвигать именно вам</h2><p>Выберите ситуацию, близкую вашему бизнесу. От неё зависит, какие страницы и материалы стоит взять в работу.</p></header>
    <div class="brief-reader"><fieldset class="brief-switch"><legend>Задача бизнеса</legend>{''.join(controls)}</fieldset>
    {''.join(spreads)}</div></div></section>'''


