def identity(key, asset):
    if key == "winline":
        return f'<img class="case-logo" src="{{PRE}}{asset("cases/winline.svg")}" alt="WINLINE" width="483" height="116">'
    return '<span class="nda-stamp">NDA</span>'


def case_index(asset):
    cards = []
    for key, project in PROJECTS.items():
        cards.append(f'''<a class="case-preview" href="{key}/">
          <img src="{{PRE}}{asset(f"cases/{key}-01.webp")}" alt="{project['client']}: {project['service']}" width="1600" height="900">
          <div><span class="project-type">{project['service']}</span><strong>{project['title']}</strong>
          <span class="case-read">Читать кейс ↗</span></div></a>''')
    return '''<section class="wrap case-directory" id="case-directory"><header><h1>Что GEO дало бизнесу?</h1>
      <p class="short-answer">Два проекта с разными задачами. Как покупатели нашли модный бренд в нейросетях и что узнала о себе команда WINLINE.</p></header>
      <div class="case-previews">'''+''.join(cards)+'</div></section>'


def case_article(key, asset):
    project = PROJECTS[key]
    facts = ''.join(f'<div><dt>{label}</dt><dd>{value}</dd></div>' for value, label in project["facts"])
    sections = []
    for question, answer, *paragraphs in project["sections"]:
        sections.append(f'<section><h2>{question}</h2><p class="short-answer">{answer}</p>'
                        + ''.join(f'<p>{p}</p>' for p in paragraphs) + '</section>')
    return f'''<article class="case-article">
      <header class="case-lead wrap"><div class="case-intro"><div class="case-identity">{identity(key, asset)}<span>{project['service']}</span></div>
      <h1>{project['heading']}</h1><p class="short-answer">{project['lead']}</p></div>
      <figure class="case-facts"><figcaption>{project['unit']}</figcaption>
      <strong>{project['figure']}</strong><dl>{facts}</dl></figure></header>
      <div class="case-narrative wrap">{''.join(sections)}</div>
      <section class="case-gallery wrap"><div><h2>Что вошло в презентацию?</h2>
      <p class="short-answer">{"Динамика за полгода, фрагменты замеров и статистика переходов по двум сайтам." if key == "fashion" else "Обзор исследования, примеры задач для команды и состав рабочего отчёта."}</p></div>
      {deck(key,project['client'],asset)}</section></article>'''
